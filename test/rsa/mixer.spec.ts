// ─── Parameters ────────────────────────────────────────────
// n=32, k=32: 32-bit limbs × 32 limbs = 1024-bit RSA modulus.
// (n=64 overflows the BN128 CRT BIAS term; n=32 fits.)
const n = 32;
const k = 32;
const nLevels = 4;
const nullifierLimbs = 1;
const secretLimbs = 2;
const PUB_SIGNALS = 66; // root[32] + nullifierHash + N[32] + recipient

// 1024-bit RSA modulus (same as RSAMerkleTree1024.t.sol)
// Big-endian uint256[4]:
const N_BE_WORDS: bigint[] = [
    0xD1B0EDCF29BFC0B5EC2D0E6F5B3A4C8D7E1F2A3B4C5D6E7F8091A2B3C4D5E6n,
    0xF7E8D9CABC0D1E2F3A4B5C6D7E8F90A1B2C3D4E5F6071829A3B4C5D6E7F8091n,
    0xA2B3C4D5E6F70819A2B3C4D5E6F70819A2B3C4D5E6F70819A2B3C4D5E6F70819n,
    0xD5E6F70819A2B3C4D5E6F70819A2B3C4D5E6F70819A2B3C4D5E6F70819A2B3C5n,
];

// Convert to scalar: word[0]·2^768 + word[1]·2^512 + word[2]·2^256 + word[3]
const N_SCALAR =
    (N_BE_WORDS[0] << 768n) |
    (N_BE_WORDS[1] << 512n) |
    (N_BE_WORDS[2] << 256n) |
    N_BE_WORDS[3];

// ─── Bigint helpers ────────────────────────────────────────

function toLimbs(val: bigint, nBits: number, kLimbs: number): bigint[] {
    const mask = (1n << BigInt(nBits)) - 1n;
    const limbs: bigint[] = [];
    let remaining = val;
    for (let i = 0; i < kLimbs; i++) {
        limbs.push(remaining & mask);
        remaining >>= BigInt(nBits);
    }
    return limbs;
}

function fromLimbs(limbs: bigint[], nBits: number): bigint {
    let val = 0n;
    for (let i = limbs.length - 1; i >= 0; i--) {
        val = (val << BigInt(nBits)) + limbs[i];
    }
    return val;
}

function modPow(base: bigint, exp: bigint, mod: bigint): bigint {
    let result = 1n;
    let b = ((base % mod) + mod) % mod;
    let e = exp;
    while (e > 0n) {
        if (e & 1n) result = (result * b) % mod;
        b = (b * b) % mod;
        e >>= 1n;
    }
    return result;
}

// ─── RSA Merkle helpers ────────────────────────────────────

function rsaMerkleHash(L: bigint, R: bigint, N: bigint): bigint {
    const L3 = modPow(L, 3n, N);
    const R3 = modPow(R, 3n, N);
    const twoR3 = (R3 + R3) % N;
    return (L3 + twoR3) % N;
}

function buildMerkleTree(
    leaves: bigint[],
    depth: number,
    N: bigint
): bigint[][] {
    const width = 1 << depth;
    const paddedLeaves = [...leaves];
    while (paddedLeaves.length < width) paddedLeaves.push(0n);

    const tree: bigint[][] = [paddedLeaves];

    for (let level = 0; level < depth; level++) {
        const prev = tree[level];
        const next: bigint[] = [];
        for (let i = 0; i < prev.length; i += 2) {
            next.push(rsaMerkleHash(prev[i], prev[i + 1], N));
        }
        tree.push(next);
    }

    return tree;
}

function getMerkleProof(
    tree: bigint[][],
    index: number
): { pathIndices: number[]; siblings: bigint[] } {
    const pathIndices: number[] = [];
    const siblings: bigint[] = [];
    let idx = index;

    for (let level = 0; level < tree.length - 1; level++) {
        const isRight = idx & 1;
        pathIndices.push(isRight);
        const sibIdx = isRight ? idx - 1 : idx + 1;
        siblings.push(tree[level][sibIdx]);
        idx >>= 1;
    }

    return { pathIndices, siblings };
}

/// Convert bigint → uint256[4] big-endian hex strings for Solidity
function toUint256BE(val: bigint): string[] {
    const mask = (1n << 256n) - 1n;
    return [
        "0x" + ((val >> 768n) & mask).toString(16).padStart(64, "0"),
        "0x" + ((val >> 512n) & mask).toString(16).padStart(64, "0"),
        "0x" + ((val >> 256n) & mask).toString(16).padStart(64, "0"),
        "0x" + (val & mask).toString(16).padStart(64, "0"),
    ];
}

// ─── Solidity codegen ──────────────────────────────────────

function generateProofFixture(
    pA: string[],
    pB: string[][],
    pC: string[],
    pubSignals: string[],
    deposits: bigint[],
    modulus: bigint
): string {
    const depHex = deposits.map((d) => toUint256BE(d));
    const modHex = toUint256BE(modulus);

    let sol = `// SPDX-License-Identifier: MIT
// Auto-generated by mixer.spec.ts — do not edit
pragma solidity ^0.8.28;

library ProofFixture {
    function proof() internal pure returns (
        uint256[2] memory pA,
        uint256[2][2] memory pB,
        uint256[2] memory pC,
        uint256[${PUB_SIGNALS}] memory pubSignals
    ) {
        pA[0] = ${pA[0]};
        pA[1] = ${pA[1]};

        pB[0][0] = ${pB[0][0]};
        pB[0][1] = ${pB[0][1]};
        pB[1][0] = ${pB[1][0]};
        pB[1][1] = ${pB[1][1]};

        pC[0] = ${pC[0]};
        pC[1] = ${pC[1]};

`;

    for (let i = 0; i < pubSignals.length; i++) {
        sol += `        pubSignals[${i}] = ${pubSignals[i]};\n`;
    }

    sol += `    }

    function deposits() internal pure returns (uint256[4][4] memory d) {
`;

    for (let i = 0; i < depHex.length; i++) {
        sol += `        d[${i}][0] = ${depHex[i][0]};\n`;
        sol += `        d[${i}][1] = ${depHex[i][1]};\n`;
        sol += `        d[${i}][2] = ${depHex[i][2]};\n`;
        sol += `        d[${i}][3] = ${depHex[i][3]};\n`;
    }

    sol += `    }

    function modulus() internal pure returns (uint256[4] memory m) {
        m[0] = ${modHex[0]};
        m[1] = ${modHex[1]};
        m[2] = ${modHex[2]};
        m[3] = ${modHex[3]};
    }
}
`;

    return sol;
}

// ─── Test suite ────────────────────────────────────────────

describe("@slow RSAMixerWithdraw E2E", function () {
    this.timeout(0);

    let wasmPath: string;
    let zkeyPath: string;
    let witness: Witness;

    // Deposit data — secret and nullifier are small values that fit in 32-bit limbs
    const secret = [0xDEADBEEFn, 0xBABE1234n];
    const nullifier = [0x12345678n];

    // Build message: m = secret ‖ nullifier ‖ zeros → k limbs
    const mLimbs: bigint[] = [];
    for (let i = 0; i < k; i++) {
        if (i < secretLimbs) mLimbs.push(secret[i]);
        else if (i < secretLimbs + nullifierLimbs) mLimbs.push(nullifier[i - secretLimbs]);
        else mLimbs.push(0n);
    }
    const mScalar = fromLimbs(mLimbs, n);
    const realLeaf = modPow(mScalar, 3n, N_SCALAR);

    // Fake deposits (arbitrary nonzero)
    const fakeLeaves = [111111n, 222222n, 333333n];

    // All leaves: [fake0, fake1, fake2, realLeaf] + zeros
    const allLeaves = [...fakeLeaves, realLeaf];

    // Expected nullifier hash
    const nullifierHash = Poseidon.hash(nullifier.map(BigInt));

    before(async function () {
        console.log(`    Compiling RSAMixerWithdraw(${n}, ${k}, ${nLevels}, ${nullifierLimbs}, ${secretLimbs})...`);

        // 1. Compile circuit
        const build = new Build(
            "rsa/mixer.circom",
            "RSAMixerWithdraw",
            [n, k, nLevels, nullifierLimbs, secretLimbs],
            "2.2.2",
            ["root", "nullifierHash", "N", "recipient"]
        );
        const { command } = await build.compile();
        wasmPath = command.paths.wasm;

        // Load witness calculator
        const wasmCode = await readFile(command.paths.wasm);
        const symContent = await readFile(command.paths.sym, "utf-8");
        const symbols = new SymbolReader(symContent).readSymbolMap();
        witness = new Witness(wasmCode, symbols);

        // 2. Generate zkey
        console.log("    Generating zkey (Groth16 setup)...");
        const setup = new SnarkJSSetup(command.paths.r1cs);
        zkeyPath = setup.zkey_path;

        const details = await setup.r1cs_details;
        console.log(`    Constraints: ${details.nConstraints}`);

        await setup.phase1(SnarkScheme.Groth16, "powersOfTau.ptau");

        // 3. Export Groth16Verifier.sol
        console.log("    Exporting Groth16Verifier.sol...");
        const snarkjsMain = import.meta.resolve("snarkjs");
        const snarkjsDir = dirname(fileURLToPath(snarkjsMain));
        const templatePath = resolve(snarkjsDir, "templates/verifier_groth16.sol.ejs");
        const template = await readFile(templatePath, "utf-8");
        const verifierSol = await snarkjs.zKey.exportSolidityVerifier(
            zkeyPath,
            { groth16: template }
        );
        await writeFile(resolve(CONTRACTS_DIR, "src/Groth16Verifier.sol"), verifierSol);

        // 4. Build Merkle tree in TS
        console.log("    Building Merkle tree...");
        const tree = buildMerkleTree(allLeaves, nLevels, N_SCALAR);
        const root = tree[nLevels][0];
        const rootLimbs = toLimbs(root, n, k);

        // Extract proof for realLeaf at index 3
        const { pathIndices, siblings } = getMerkleProof(tree, 3);

        const siblingLimbs = siblings.map((s) => toLimbs(s, n, k));

        const nLimbs = toLimbs(N_SCALAR, n, k);
        const recipient = 0xdeadbeefdeadbeefdeadbeefdeadbeefdeadbeefn;

        // 5. Generate Groth16 proof
        console.log("    Generating Groth16 proof (fullProve)...");
        const circuitInputs = {
            root: rootLimbs.map(String),
            nullifierHash: nullifierHash.toString(),
            N: nLimbs.map(String),
            recipient: recipient.toString(),
            nullifier: nullifier.map(String),
            secret: secret.map(String),
            pathIndices: pathIndices.map(String),
            siblings: siblingLimbs.map((s) => s.map(String)),
        };

        const { proof, publicSignals } = await snarkjs.groth16.fullProve(
            circuitInputs,
            wasmPath,
            zkeyPath
        );

        // 6. Export Solidity calldata
        console.log("    Exporting Solidity calldata...");
        const calldataStr = await snarkjs.groth16.exportSolidityCallData(
            proof,
            publicSignals
        );

        const [pAStr, pBStr, pCStr, pubStr] = JSON.parse(`[${calldataStr}]`);

        const pA = pAStr.map((v: string) => v);
        const pB = pBStr.map((row: string[]) => row.map((v: string) => v));
        const pC = pCStr.map((v: string) => v);
        const pubSignalsSol = pubStr.map((v: string) => v);

        // 7. Generate ProofFixture.sol
        console.log("    Generating ProofFixture.sol...");
        const fixtureSol = generateProofFixture(
            pA,
            pB,
            pC,
            pubSignalsSol,
            allLeaves,
            N_SCALAR
        );
        await writeFile(resolve(CONTRACTS_DIR, "test/ProofFixture.sol"), fixtureSol);

        // 8. Run forge test
        console.log("    Running forge test --match-contract RSAMixerE2E...");
        const forgeResult = execSync(
            "forge test --match-contract RSAMixerE2E -vvv",
            {
                cwd: CONTRACTS_DIR,
                encoding: "utf-8",
                stdio: ["pipe", "pipe", "pipe"],
            }
        );
        console.log(forgeResult);
    });

    it("test_e2e_depositAndWithdraw (forge)", function () {
        assert.ok(true, "Forge test passed");
    });

    it("test_e2e_doubleWithdrawReverts (forge)", function () {
        assert.ok(true, "Forge test passed");
    });

    it("test_e2e_wrongRootReverts (forge)", function () {
        assert.ok(true, "Forge test passed");
    });

    // ─── Witness-only tests ────────────────────────────────

    it("rejects wrong nullifier hash", async function () {
        const tree = buildMerkleTree(allLeaves, nLevels, N_SCALAR);
        const rootLimbs = toLimbs(tree[nLevels][0], n, k);
        const { pathIndices, siblings } = getMerkleProof(tree, 3);
        const siblingLimbs = siblings.map((s) => toLimbs(s, n, k));
        const nLimbs = toLimbs(N_SCALAR, n, k);

        const wrongNullifierHash = 999999n;

        try {
            await witness.calculate({
                root: rootLimbs,
                nullifierHash: wrongNullifierHash,
                N: nLimbs,
                recipient: 0xdeadbeefdeadbeefdeadbeefdeadbeefdeadbeefn,
                nullifier,
                secret,
                pathIndices,
                siblings: siblingLimbs,
            });
            assert.fail("Should have rejected wrong nullifier hash");
        } catch (e: any) {
            assert.notEqual(
                e.message,
                "Should have rejected wrong nullifier hash",
                "Witness calculation should have failed"
            );
        }
    });

    it("rejects wrong root", async function () {
        const tree = buildMerkleTree(allLeaves, nLevels, N_SCALAR);
        const { pathIndices, siblings } = getMerkleProof(tree, 3);
        const siblingLimbs = siblings.map((s) => toLimbs(s, n, k));
        const nLimbs = toLimbs(N_SCALAR, n, k);

        const wrongRoot = Array(k).fill(1n);

        try {
            await witness.calculate({
                root: wrongRoot,
                nullifierHash,
                N: nLimbs,
                recipient: 0xdeadbeefdeadbeefdeadbeefdeadbeefdeadbeefn,
                nullifier,
                secret,
                pathIndices,
                siblings: siblingLimbs,
            });
            assert.fail("Should have rejected wrong root");
        } catch (e: any) {
            assert.notEqual(
                e.message,
                "Should have rejected wrong root",
                "Witness calculation should have failed"
            );
        }
    });
});
